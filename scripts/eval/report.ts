/** Rendering for the eval harness: the summary table, the compatibility matrix, the pick. */
import { type ProfileResult, type Summary, summarize } from './harness.ts';
import { TASK_SET_VERSION, TASKS } from './tasks.ts';

/** A local profile must pass at least this share of the tasks to be recommended. */
export const MIN_RECOMMEND_PASS_RATE = 0.7;

const pct = (x: number) => `${Math.round(x * 100)}%`;

function fmtCost(cost: number | undefined): string {
  if (cost === undefined) return '—';
  return cost === 0 ? 'free' : `$${cost.toFixed(4)}`;
}

function fmtRate(s: Summary): string {
  return s.tokensPerSecond === undefined ? '—' : s.tokensPerSecond.toFixed(1);
}

/**
 * Best first. Runs of the full task set come before subsets (a 3/3 on three tasks says less than
 * 9/10 on ten), then pass rate, valid-call rate, speed, and finally name for a stable order.
 */
export function rank(results: ProfileResult[]): ProfileResult[] {
  const complete = (r: ProfileResult) => (r.tasks.length === TASKS.length ? 1 : 0);
  return [...results].sort((a, b) => {
    const x = summarize(a);
    const y = summarize(b);
    return (
      complete(b) - complete(a) ||
      y.passRate - x.passRate ||
      (y.validRate ?? 0) - (x.validRate ?? 0) ||
      (y.tokensPerSecond ?? 0) - (x.tokensPerSecond ?? 0) ||
      a.profile.localeCompare(b.profile)
    );
  });
}

/**
 * The profile to use as the default `local`: the best local profile that ran the full task set
 * and passed at least 70%. Undefined until some local profile gets there.
 */
export function recommendLocal(results: ProfileResult[]): ProfileResult | undefined {
  const candidates = results.filter(
    (r) =>
      r.local &&
      r.tasks.length === TASKS.length &&
      summarize(r).passRate >= MIN_RECOMMEND_PASS_RATE,
  );
  return rank(candidates)[0];
}

/** The summary table (markdown), best first. Used on the terminal and in the matrix. */
export function renderSummary(results: ProfileResult[]): string {
  const partial = results.some((r) => r.tasks.length < TASKS.length);
  const rows = rank(results).map((r) => {
    const s = summarize(r);
    const pass = `${s.passed}/${s.total}${r.tasks.length < TASKS.length ? ' †' : ''}`;
    return `| ${r.profile} | ${r.model} | ${r.local ? 'local' : 'remote'} | ${r.toolMode} | ${pass} | ${s.validRate === undefined ? '—' : pct(s.validRate)} | ${s.repairedCalls} | ${fmtRate(s)} | ${fmtCost(s.cost)} | ${s.avgSteps.toFixed(1)} |`;
  });
  const lines = [
    '| Profile | Model | Where | Tools | Pass | Valid calls | Repaired | tok/s | Cost | Avg steps |',
    '|---|---|---|---|---|---|---|---|---|---|',
    ...rows,
  ];
  if (partial) lines.push('', '† a subset of the tasks was run.');
  return lines.join('\n');
}

function recommendation(results: ProfileResult[]): string {
  const best = recommendLocal(results);
  if (best) {
    const s = summarize(best);
    return `**\`${best.profile}\`** (${best.model}, tools: ${best.toolMode}) is the best local profile: ${s.passed}/${s.total} tasks, ${s.validRate === undefined ? 'no tool calls' : `${pct(s.validRate)} valid tool calls`}, ${fmtRate(s)} tok/s. Make it the default \`local\` profile.`;
  }
  const local = results.filter((r) => r.local);
  if (local.length === 0) return 'No local profile has been run yet.';
  return `No local profile has passed ${pct(MIN_RECOMMEND_PASS_RATE)} of the full task set yet. Keep the current defaults until one does.`;
}

/** The whole compatibility matrix, as the markdown committed in docs/COMPATIBILITY.md. */
export function renderMatrix(results: ProfileResult[], now = new Date()): string {
  const head = [
    '# Compatibility matrix',
    '',
    `Generated by \`bun run eval\` on ${now.toISOString().slice(0, 10)}. Task set v${TASK_SET_VERSION} (${TASKS.length} tasks). Do not edit by hand: re-run the harness and regenerate with \`bun run eval --report --matrix docs/COMPATIBILITY.md\`.`,
    '',
  ];
  if (results.length === 0) {
    return [
      ...head,
      '_No results yet._ Run `bun run eval -P <profile>` for each profile you care about, then regenerate this file. See the README section "Evaluating models".',
      '',
    ].join('\n');
  }
  const ranked = rank(results);
  const taskRows = TASKS.map((t) => {
    const cells = ranked.map((r) => {
      const hit = r.tasks.find((x) => x.id === t.id);
      return hit ? (hit.pass ? '✓' : '✗') : '—';
    });
    return `| ${t.id} | ${t.category} | ${cells.join(' | ')} |`;
  });
  const failures = ranked.flatMap((r) =>
    r.tasks.filter((x) => !x.pass).map((x) => `- **${r.profile}** · ${x.id}: ${x.reason}`),
  );
  return [
    ...head,
    '## Summary',
    '',
    renderSummary(results),
    '',
    '## Tasks',
    '',
    `| Task | Category | ${ranked.map((r) => r.profile).join(' | ')} |`,
    `|---|---|${ranked.map(() => '---').join('|')}|`,
    ...taskRows,
    '',
    '## Failures',
    '',
    ...(failures.length > 0 ? failures : ['None.']),
    '',
    '## Recommended `local` profile',
    '',
    recommendation(results),
    '',
    '## How to read this',
    '',
    '- **Pass**: tasks whose verifier passed. Verifiers inspect the workspace afterwards (exact file contents, `bun test`, the final answer); they never call a model.',
    '- **Valid calls**: share of the model’s tool calls that were valid on the first try (known tool, valid arguments, not empty).',
    '- **Repaired**: tool calls whose malformed JSON mrig salvaged before running.',
    '- **tok/s**: output tokens per second after the first token, when the provider reports it; otherwise output tokens over total time waiting on the model.',
    '- **Cost**: estimated from the pricing table; `free` for local models, `—` when pricing is unknown.',
    '',
  ].join('\n');
}

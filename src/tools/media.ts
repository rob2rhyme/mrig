/**
 * Helpers shared by the media tools (T4 image, T5 speak and transcribe): file names, never
 * overwriting, saving, provider warnings and prices.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, extname, isAbsolute, join, resolve } from 'node:path';
import { displayPath } from '../util/paths.ts';

/** A file name from a prompt or text: 20261106-091500-a-red-fox.png. */
export function mediaFileName(text: string, now: Date, ext: string): string {
  const stamp = now.toISOString().replace(/[-:]/g, '').replace('T', '-').slice(0, 15);
  const slug = text
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40)
    .replace(/-+$/, '');
  return `${stamp}${slug ? `-${slug}` : ''}${ext}`;
}

/** `base.png`, or `base-2.png`, `base-3.png`… so an existing file is never overwritten. */
export function freePath(path: string): string {
  if (!existsSync(path)) return path;
  const ext = extname(path);
  const stem = path.slice(0, path.length - ext.length);
  for (let i = 2; ; i++) {
    const p = `${stem}-${i}${ext}`;
    if (!existsSync(p)) return p;
  }
}

/**
 * Save generated bytes: at the requested path, else under `dir` with a name from `text`. Never
 * overwrites. Returns the path as shown to the model (relative to cwd when inside it).
 */
export function saveMedia(opts: {
  cwd: string;
  dir: string;
  requested?: string;
  text: string;
  ext: string;
  now: Date;
  bytes: Uint8Array;
}): string {
  const base = opts.requested
    ? isAbsolute(opts.requested)
      ? opts.requested
      : resolve(opts.cwd, opts.requested)
    : join(resolve(opts.cwd, opts.dir), mediaFileName(opts.text, opts.now, opts.ext));
  const path = freePath(base);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, opts.bytes);
  return displayPath(opts.cwd, path);
}

/** One line for a provider warning (an unsupported size or voice, for example). */
export function describeWarning(w: object): string {
  const r = w as { type?: string; message?: string; feature?: string; details?: string };
  if (r.message) return r.message;
  if (r.feature) return `${r.type ?? 'note'}: ${r.feature}${r.details ? ` (${r.details})` : ''}`;
  return JSON.stringify(w);
}

/** "~$0.04", "~$0.0012", or "price unknown". */
export function money(usd: number | undefined): string {
  return usd === undefined ? 'price unknown' : `~$${usd < 0.01 ? usd.toFixed(4) : usd.toFixed(2)}`;
}
